/**
 * Playwright configuration — end-to-end browser tests.
 *
 * Tests live under `tests/e2e/`. We boot the Next.js dev server automatically
 * (or reuse one if already running on :3000), then point Chromium at it.
 *
 * Network requests to Signal Ocean are intercepted per-test using Playwright's
 * `page.route()` API — there's no production Signal Ocean call from any test.
 */
